/** File-safe art name: "N-ZAP '85" -> "n-zap-85". */
function artName(name: string): string {
  return name.toLowerCase().replace(/[.'+]/g, "").replace(/&/g, "and").replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
}

