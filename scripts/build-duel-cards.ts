/**
 * Daily Duel: write the card facts for every card the game uses (each trainer's team and the player
 * pool) to src/data/originals/duel/cards.generated.ts, read from our catalog (`tcg_cards`, 0 credits).
 *
 *   npx tsx -r ./scripts/server-only-shim.cjs scripts/build-duel-cards.ts
 *
 * Run it after scripts/populate-duel-cards.ts (which stores any card the catalog was missing) and
 * after any change to the roster or the pool. Fails if a card is missing from the catalog or can't
 * play (see src/data/originals/duel/cardRules.ts).
 *
 * It also writes src/data/originals/duel/trainer-art.generated.ts: for each trainer's picture
 * (their own Supporter card from trainer-cards.ts, or their ace's card when they have none) the
 * image exactly as Scrydex returned it and its width over its height, read from the image itself
 * (Scrydex's medium images are 367 × 512, older cards 367 × 504).
 */

import { config } from "dotenv";
config({ path: ".env.local" });

import { writeFileSync } from "node:fs";
import sharp from "sharp";
import { createServiceClient } from "../src/lib/supabase/admin";
import { DUEL_TRAINERS } from "../src/data/originals/duel/trainers";
import { DUEL_TRAINER_CARDS } from "../src/data/originals/duel/trainer-cards";
import { personOf } from "../src/lib/originals/duel/rules";
import { DUEL_POOL } from "../src/data/originals/duel/pool";
import { canHit, toDuelCard, type DuelCatalogRow } from "../src/data/originals/duel/cardRules";
import type { DuelCard } from "../src/lib/originals/duel/types";
import { gsDay } from "../src/lib/time/gsClock";

const OUT = "src/data/originals/duel/cards.generated.ts";
const ART_OUT = "src/data/originals/duel/trainer-art.generated.ts";

/** An image's width over its height, read from the image (null when it can't be read). */
async function ratioOf(src: string): Promise<number | null> {
  try {
    const res = await fetch(src, { signal: AbortSignal.timeout(15000) });
    if (!res.ok) return null;
    const meta = await sharp(Buffer.from(await res.arrayBuffer())).metadata();
    return meta.width && meta.height ? Math.round((meta.width / meta.height) * 10000) / 10000 : null;
  } catch {
    return null;
  }
}

/**
 * Each trainer's picture card: their own Supporter card, or the ace (the last card) of each of
 * their teams when they have none. The image as Scrydex returned it, and its shape.
 */
async function writeTrainerArt(cards: Record<string, DuelCard>) {
  const own = [...new Set(Object.values(DUEL_TRAINER_CARDS).flatMap((p) => (p.card ? [p.card] : [])))];
  const aces = [...new Set(DUEL_TRAINERS.filter((t) => !DUEL_TRAINER_CARDS[personOf(t)]?.card).map((t) => t.team[t.team.length - 1]))];
  const svc = createServiceClient();
  const { data, error } = await svc.from("tcg_cards").select("id, images").in("id", own);
  if (error) throw error;
  const img = new Map(((data ?? []) as { id: string; images: { medium?: string; small?: string } | null }[]).map((r) => [r.id, r.images?.medium ?? r.images?.small ?? null]));
  const problems: string[] = [];
  const art: Record<string, { img: string; ratio: number }> = {};
  const todo = [...own.map((id) => ({ id, src: img.get(id) ?? null })), ...aces.map((id) => ({ id, src: cards[id]?.img ?? null }))];
  for (let i = 0; i < todo.length; i += 8) {
    await Promise.all(todo.slice(i, i + 8).map(async ({ id, src }) => {
      if (!src) { problems.push(`${id}: no picture stored (run populate-duel-cards.ts --trainers --run)`); return; }
      const ratio = await ratioOf(src);
      if (!ratio) { problems.push(`${id}: couldn't read ${src}`); return; }
      art[id] = { img: src, ratio };
    }));
  }
  if (problems.length) {
    console.error(`${problems.length} picture problem(s):\n  ${problems.join("\n  ")}`);
    process.exit(1);
  }
  const body = Object.keys(art).sort().map((id) => `  ${JSON.stringify(id)}: ${JSON.stringify(art[id])},`).join("\n");
  writeFileSync(ART_OUT, `/**
 * Daily Duel: each trainer's picture card (their own Supporter card from trainer-cards.ts, or their
 * ace's card when they have none): the image exactly as Scrydex returned it and its width over its
 * height. GENERATED by scripts/build-duel-cards.ts on ${gsDay()}; don't edit by hand.
 */

export const DUEL_TRAINER_ART: Record<string, { img: string; ratio: number }> = {
${body}
};
`);
  console.log(`Wrote ${ART_OUT}: ${own.length} trainer cards, ${aces.length} aces.`);
}

async function main() {
  const ids = [...new Set([...DUEL_TRAINERS.flatMap((t) => t.team), ...DUEL_POOL])];
  const svc = createServiceClient();
  const rows = new Map<string, DuelCatalogRow>();
  for (let i = 0; i < ids.length; i += 200) {
    const { data, error } = await svc.from("tcg_cards")
      .select("id, name, supertype, subtypes, types, hp, attacks, weaknesses, rarity, language_code, images")
      .in("id", ids.slice(i, i + 200));
    if (error) throw error;
    for (const r of (data ?? []) as DuelCatalogRow[]) rows.set(r.id, r);
  }

  const cards: Record<string, DuelCard> = {};
  const problems: string[] = [];
  for (const id of ids) {
    const row = rows.get(id);
    if (!row) { problems.push(`${id}: not in tcg_cards (run populate-duel-cards.ts --warm --run)`); continue; }
    const card = toDuelCard(row);
    if (!card) { problems.push(`${id} ${row.name}: can't play (no type, HP or damaging move)`); continue; }
    if (!canHit(card)) { problems.push(`${id} ${row.name}: every damaging move costs more than 4 Energy`); continue; }
    cards[id] = card;
  }
  if (problems.length) {
    console.error(`${problems.length} problem(s):\n  ${problems.join("\n  ")}`);
    process.exit(1);
  }

  const body = Object.keys(cards).sort().map((id) => `  ${JSON.stringify(id)}: ${JSON.stringify(cards[id])},`).join("\n");
  writeFileSync(OUT, `/**
 * Daily Duel: the numbers on every card the game uses (each trainer's team and the player pool),
 * read from our Scrydex catalog (\`tcg_cards\`). GENERATED by scripts/build-duel-cards.ts on
 * ${gsDay()}; don't edit by hand. Rerun it after changing the roster or the pool:
 *   npx tsx -r ./scripts/server-only-shim.cjs scripts/build-duel-cards.ts
 * Images are the medium URLs exactly as Scrydex returned them.
 */

import type { DuelCard } from "@/lib/originals/duel/types";

export const DUEL_CARDS: Record<string, DuelCard> = {
${body}
};
`);
  console.log(`Wrote ${OUT}: ${Object.keys(cards).length} cards (${DUEL_TRAINERS.length} trainers, ${DUEL_POOL.length} in the pool).`);
  await writeTrainerArt(cards);
}

main().catch((e) => { console.error(e); process.exit(1); });
